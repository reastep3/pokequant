import Link from "next/link";
import { api } from "@/lib/api";
import { money, num, pct, short, z } from "@/lib/format";

export const dynamic = "force-dynamic";

const KIND: Record<string, string> = {
  grading_arb: "GRADING ARB", jp_en_pairs: "JP/EN PAIRS", sealed_ev: "SEALED EV", bubble: "BUBBLE", drawdown_recovery: "DD RECOVERY",
};

export default async function SignalsPage() {
  const data = await api.signals().catch(() => ({ count: 0, rows: [] }));
  return (
    <div className="panel m-2">
      <div className="panel-h"><span>Signal feed · |z| ≥ 2σ spreads, mispriced sealed, bubble premia, unrecovered drawdowns below fair</span><span className="normal-case tracking-normal dim">{data.count} active</span></div>
      <table className="grid-table">
        <thead><tr><th>Dir</th><th>Kind</th><th>Ticker</th><th>Headline</th><th className="num">Strength</th><th className="num">Px</th><th className="num">Fair</th><th className="num">Kelly f</th><th>Created</th><th>Expires</th></tr></thead>
        <tbody>
          {data.rows.length === 0 && <tr><td colSpan={10} className="muted p-3">No active signals. They are generated by the analytics job when spreads breach thresholds.</td></tr>}
          {data.rows.map((s) => (
            <tr key={s.id}>
              <td><span className={`tag ${s.direction}`}>{s.direction.toUpperCase()}</span></td>
              <td className="dim">{KIND[s.kind] ?? s.kind}</td>
              <td><Link href={`/asset/${s.asset_id}`} className="amber">{s.ticker}</Link> <span className="muted">{s.grade_key}</span></td>
              <td>{s.headline}</td>
              <td className="num tnum">{s.kind === "grading_arb" || s.kind === "jp_en_pairs" ? z(s.strength) : s.kind === "sealed_ev" ? `EV/px ${num(1 + s.strength / 10, 2)}` : s.kind === "bubble" ? pct(s.strength / 5, 0) : num(s.strength, 1)}</td>
              <td className="num tnum">{money(s.payload?.market_price)}</td>
              <td className="num tnum">{money(s.payload?.fair_value)}</td>
              <td className="num tnum">{pct(s.payload?.kelly_fraction_scaled, 1, false)}</td>
              <td className="dim">{short(s.created_at)}</td>
              <td className="dim">{short(s.expires_at)}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
